export function topicsByLevel(levelId) {
  return ENGLISH_TOPICS.filter((t) => t.level === levelId)
}

export function topicsByArea(area) {
  if (!area) return ENGLISH_TOPICS
  return ENGLISH_TOPICS.filter((t) => t.area === area)
}

export function topicById(id) {
  return ENGLISH_TOPICS.find((t) => t.id === id) ?? null
}

export function curriculumOutline(maxPerLevel = 8) {
  return ENGLISH_LEVELS.map((level) => {
    const topics = topicsByLevel(level.id)
    const shown = topics.slice(0, maxPerLevel)
    const more = topics.length - shown.length
    const lines = shown.map((t) => `  - ${t.name} (${t.area}): ${t.goal}`)
    if (more > 0) lines.push(`  - …and ${more} more topics at this level`)
    return `${level.name}:\n${lines.join('\n')}`
  }).join('\n\n')
}

export function suggestTopics(levelId, limit = 4) {
  const pool = levelId ? topicsByLevel(levelId) : ENGLISH_TOPICS
  return pool.slice(0, limit)
}
